import { Category, EquipKind, Exercise, ExerciseSet, MuscleGroup } from '../types/workout';

// Set schemes: c = 12/10/8, i = 15/12/10, h = 10/8/6, rN = 3 x N reps, tN = 3 timed holds of N s, mN = one N-minute session
type Scheme = 'c' | 'i' | 'h' | `r${string}` | `t${number}` | `m${number}`;
const setsFor = (s: Scheme): ExerciseSet[] => {
  const reps = (r: string[]) => r.map((x, i) => ({ setNum: i + 1, targetReps: x }));
  if (s === 'c') return reps(['12', '10', '8']);
  if (s === 'i') return reps(['15', '12', '10']);
  if (s === 'h') return reps(['10', '8', '6']);
  if (s[0] === 'r') return reps([s.slice(1), s.slice(1), s.slice(1)]);
  const n = Number(s.slice(1));
  if (s[0] === 't') return [1, 2, 3].map((k) => ({ setNum: k, targetDescription: `${n} sec`, targetSeconds: n, isTimed: true }));
  return [{ setNum: 1, targetDescription: `${n} min steady`, targetSeconds: n * 60, isTimed: true }];
};

interface L {
  id: string; name: string; cat: Category; eq: [string, EquipKind]; area: string;
  p: MuscleGroup[]; s?: MuscleGroup[]; pm: string[]; sm: string[];
  sets?: Scheme; rest?: number; d: string; steps: string[]; tips: string[]; bad: string[];
}

const make = (x: L): Exercise => ({
  id: x.id, name: x.name, category: x.cat, equipment: { label: x.eq[0], kind: x.eq[1] }, targetArea: x.area,
  primaryMuscles: x.pm, secondaryMuscles: x.sm, anatomyHighlightGroups: x.p, secondaryGroups: x.s ?? [],
  sets: setsFor(x.sets ?? 'c'), defaultRestSeconds: x.rest ?? 60, description: x.d,
  stepByStep: x.steps, formTips: x.tips, commonMistakes: x.bad,
});

